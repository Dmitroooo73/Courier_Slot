"""Rebuild frontend/src/geo/moscowZones.ts from OpenStreetMap okrug boundaries (ODbL).

Needs internet once and `pip install shapely`. Downloads are cached in data/raw/geo/.
Run from the project root: python tools/build_moscow_map.py
"""
import json
import math
import sys
import time
from pathlib import Path
from urllib.parse import urlencode
from urllib.request import Request, urlopen

import shapely
from shapely.geometry import MultiPolygon, Polygon, shape
from shapely.ops import polylabel, unary_union


ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / "data" / "raw" / "geo"
OUTPUT = ROOT / "frontend" / "src" / "geo" / "moscowZones.ts"
USER_AGENT = "pult-dostavki-student-project/1.0"
ZONES = {
    "center": ["Центральный"],
    "north": ["Северный", "Северо-Восточный"],
    "east": ["Восточный", "Юго-Восточный"],
    "south": ["Южный", "Юго-Западный"],
    "west": ["Западный"],
    "northwest": ["Северо-Западный"],
}
SHORT = {"Центральный": "ЦАО", "Северный": "САО", "Северо-Восточный": "СВАО", "Восточный": "ВАО",
         "Юго-Восточный": "ЮВАО", "Южный": "ЮАО", "Юго-Западный": "ЮЗАО", "Западный": "ЗАО",
         "Северо-Западный": "СЗАО"}
RIVER_RELATION = "R389341"  # Москва-река
TOLERANCE = 0.004
MIN_AREA = 0.0004
WIDTH = 440


def fetch(name: str, url: str) -> list:
    path = CACHE / name
    if not path.is_file():
        CACHE.mkdir(parents=True, exist_ok=True)
        with urlopen(Request(url, headers={"User-Agent": USER_AGENT}), timeout=60) as response:
            path.write_bytes(response.read())
        time.sleep(1.5)  # Nominatim usage policy: at most one request per second
    return json.loads(path.read_text(encoding="utf-8"))


def okrug(name: str):
    query = urlencode({"q": f"{name} административный округ, Москва", "format": "jsonv2",
                       "polygon_geojson": 1, "limit": 1})
    found = fetch(f"okrug-{SHORT[name]}.json", f"https://nominatim.openstreetmap.org/search?{query}")[0]
    return shape(found["geojson"]).buffer(0)


def parts(geometry) -> list[Polygon]:
    return list(geometry.geoms) if isinstance(geometry, MultiPolygon) else [geometry]


def main() -> None:
    zones = {}
    for zone, names in ZONES.items():
        merged = unary_union([okrug(name) for name in names]).buffer(0.0004).buffer(-0.0004)
        # Keep the city body: drop small exclaves and pieces far west of 37.3° E.
        kept = [part for part in parts(merged) if part.area >= MIN_AREA and part.centroid.x > 37.3]
        zones[zone] = MultiPolygon(kept) if len(kept) > 1 else kept[0]
    # Simplify shared borders together so neighbouring zones still meet exactly.
    zones = dict(zip(zones, shapely.coverage_simplify(list(zones.values()), TOLERANCE)))
    city = unary_union(list(zones.values()))

    k = math.cos(math.radians(55.75))
    minx, miny, maxx, maxy = city.bounds
    pad = 14
    scale = (WIDTH - 2 * pad) / ((maxx - minx) * k)
    height = round((maxy - miny) * scale + 2 * pad)

    def point(lon: float, lat: float) -> str:
        return f"{round((lon - minx) * k * scale + pad, 1):g} {round((maxy - lat) * scale + pad, 1):g}"

    def path(polygon: Polygon) -> str:
        return "".join("M" + " ".join(point(*c) for c in ring.coords[:-1]) + "Z"
                       for ring in [polygon.exterior, *polygon.interiors])

    river_query = urlencode({"osm_ids": RIVER_RELATION, "format": "json", "polygon_geojson": 1, "polygon_threshold": 0.0003})
    river = fetch("river.json", f"https://nominatim.openstreetmap.org/lookup?{river_query}")[0]["geojson"]
    river = shape(river).intersection(city.buffer(0.004)).simplify(0.0015)
    river_path = " ".join("M" + " ".join(point(*c) for c in line.coords)
                          for line in getattr(river, "geoms", [river]) if line.length > 0.005)

    lines = [
        "// Generated by tools/build_moscow_map.py from OpenStreetMap okrug boundaries",
        "// (© OpenStreetMap contributors, ODbL 1.0). Zones are unions of okrugs; see docs/map.md.",
        "export interface ZoneShape { path: string; label: readonly [number, number]; okrugs: readonly string[] }",
        "",
        f"export const MAP_VIEWBOX = \"0 0 {WIDTH} {height}\";",
        "export const MOSCOW_ZONES: Record<string, ZoneShape> = {",
    ]
    for zone, geometry in zones.items():
        label = polylabel(max(parts(geometry), key=lambda part: part.area), tolerance=0.001)
        x, y = point(label.x, label.y).split()
        lines += [f"  {zone}: {{", f"    okrugs: {json.dumps([SHORT[name] for name in ZONES[zone]], ensure_ascii=False)},",
                  f"    label: [{x}, {y}],", f"    path: {json.dumps(''.join(path(part) for part in parts(geometry)))},", "  },"]
    lines += ["};", "", f"export const MOSCOW_RIVER = {json.dumps(river_path)};", ""]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{OUTPUT.relative_to(ROOT)}: {OUTPUT.stat().st_size} байт", file=sys.stderr)


if __name__ == "__main__":
    main()
